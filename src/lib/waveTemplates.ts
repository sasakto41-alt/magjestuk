/**
 * Текст запроса свободности в /dep.
 * Пример: /dep to ALL: Свободно ли следующее время для гос. волн: 18:00 18:20 18:40?
 */
export function buildAskCommand(times: string[]): string {
  return `/dep to ALL: Свободно ли следующее время для гос. волн: ${times.join(' ')}?`;
}

/**
 * Текст занятия гос. волны.
 * Пример: /dep to ALL: Фракция SANG занимает следующее время для гос. волн: 18:00 18:20 18:40
 */
export function buildOccupyCommand(faction: string, times: string[]): string {
  return `/dep to ALL: Фракция ${faction} занимает следующее время для гос. волн: ${times.join(' ')}`;
}

